  if (!S.sdrag) return; const t = sheetTile(e), a = S.sdrag.a;
  S.sheetSel = {c: Math.min(a.c, t.c), r: Math.min(a.r, t.r), cols: Math.abs(a.c - t.c) + 1, rows: Math.abs(a.r - t.r) + 1}; drawSheet();
