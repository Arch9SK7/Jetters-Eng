function key(e) {
  if (e.target.matches('input,select,textarea')) return;
  const k = e.key, ctrl = e.ctrlKey || e.metaKey;
  if (ctrl && k.toLowerCase() === 'z') { e.preventDefault(); e.shiftKey ? redo() : undo(); return; }
  if (ctrl && k.toLowerCase() === 'y') { e.preventDefault(); redo(); return; }
  if (ctrl && k.toLowerCase() === 'd') { e.preventDefault(); dup(); return; }
  if (ctrl && k.toLowerCase() === 'a') { e.preventDefault(); S.sel = new Set(frame().map((_, i) => i)); drawAll(); return; }
  if (k === 'Delete' || k === 'Backspace') { e.preventDefault(); del(); return; }
  if (k === '[') { stopPlay(); setFrame(S.cur - 1); return; }
  if (k === ']') { stopPlay(); setFrame(S.cur + 1); return; }
  if (k === 'Escape') { S.sel.clear(); S.sheetSel = null; drawAll(); return; }
  const d = {ArrowLeft: [-1, 0], ArrowRight: [1, 0], ArrowUp: [0, -1], ArrowDown: [0, 1]}[k];
  if (d && S.sel.size) { e.preventDefault(); const m = e.shiftKey ? 8 : 1; pushUndo();
    for (const i of S.sel) { const p = frame()[i]; p.x += d[0] * m; p.y += d[1] * m; clampPiece(p); } drawAll(); }
}

