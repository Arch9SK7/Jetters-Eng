// ---------------------------------------------------------------- state
function setDirty(v) { S.dirty = v; const st = $('#status'); st.textContent = v ? 'Unsaved changes' : 'Saved'; st.className = 'status' + (v ? ' dirty' : ''); App.dirtyChanged(); }
function snapshot() { return JSON.stringify(S.frames); }
function pushUndo() { S.undo.push(snapshot()); if (S.undo.length > 200) S.undo.shift(); S.redo = []; setDirty(true); }
function undo() { if (!S.undo.length) return; S.redo.push(snapshot()); S.frames = JSON.parse(S.undo.pop()); fixSel(); setDirty(true); drawAll(); }
function redo() { if (!S.redo.length) return; S.undo.push(snapshot()); S.frames = JSON.parse(S.redo.pop()); fixSel(); setDirty(true); drawAll(); }
function fixSel() { const n = frame().length; for (const i of [...S.sel]) if (i >= n) S.sel.delete(i); }
function frame() { return S.frames[S.cur] || []; }
function setFrame(i) { if (!S.frames.length) return; S.cur = (i + S.frames.length) % S.frames.length; S.sel.clear(); drawAll(); }
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);

// ------------------------------------------------------------- geometry
function box(p) { const d = p.a0x & 2; return {x: p.x + (d ? p.w / 2 : 0), y: p.y + (d ? p.h / 2 : 0), w: p.w, h: p.h}; }
function* cells(p) {
  const b = box(p), cw = p.w / 8, ch = p.h / 8;
  for (let ty = 0; ty < ch; ty++) for (let tx = 0; tx < cw; tx++) {
    const sx = p.hflip ? cw - 1 - tx : tx, sy = p.vflip ? ch - 1 - ty : ty;
    yield {t: p.tile + ty * 32 + tx, x: b.x + sx * 8, y: b.y + sy * 8};
  }
}
function tilesOf(f) { const s = new Set(); for (const p of f) for (const c of cells(p)) s.add(c.t); return s; }

// --------------------------------------------------------------- render
const cv = $('#cv'), ctx = cv.getContext('2d');
const zoom = () => +$('#zoom').value;
function drawAll() { if (!S.data) return; drawFrame(); drawSheet(); renderFrames(); renderPieces(); renderInspector(); }
function drawPieces(c, f, alpha) {
  c.globalAlpha = alpha;
  const sh = S.sheetImg, cols = (S.data.sheetW / 8) | 0, ntile = cols * ((S.data.sheetH / 8) | 0);
  for (let i = f.length - 1; i >= 0; i--) {
    const p = f[i];
    for (const cl of cells(p)) {
      if (sh && cl.t < ntile) {
        c.save(); c.translate(cl.x + (p.hflip ? 8 : 0), cl.y + (p.vflip ? 8 : 0)); c.scale(p.hflip ? -1 : 1, p.vflip ? -1 : 1);
        c.drawImage(sh, (cl.t % cols) * 8, Math.floor(cl.t / cols) * 8, 8, 8, 0, 0, 8, 8); c.restore();
      } else if (cl.t >= ntile) { c.fillStyle = 'rgba(255,0,255,.5)'; c.fillRect(cl.x, cl.y, 8, 8); }
    }
  }
  c.globalAlpha = 1;
}
function drawFrame() {
  const z = zoom(), W = S.world; cv.width = W.w * z; cv.height = W.h * z;
  ctx.imageSmoothingEnabled = false;
  ctx.setTransform(1, 0, 0, 1, 0, 0); ctx.fillStyle = '#0e1014'; ctx.fillRect(0, 0, cv.width, cv.height);
  ctx.setTransform(z, 0, 0, z, -W.x0 * z, -W.y0 * z);
  if (!S.data) return;
  if ($('#gridChk').checked) {
    ctx.strokeStyle = 'rgba(255,255,255,.06)'; ctx.lineWidth = 1 / z; ctx.beginPath();
    for (let x = W.x0; x <= W.x0 + W.w; x += 8) { ctx.moveTo(x, W.y0); ctx.lineTo(x, W.y0 + W.h); }
    for (let y = W.y0; y <= W.y0 + W.h; y += 8) { ctx.moveTo(W.x0, y); ctx.lineTo(W.x0 + W.w, y); }
    ctx.stroke();
  }
  if ($('#onionChk').checked && S.cur > 0) drawPieces(ctx, S.frames[S.cur - 1], .28);
  const showRom = $('#romChk').checked;
  drawPieces(ctx, showRom ? S.data.romFrames[S.cur] || [] : frame(), 1);
  if ($('#outlineChk').checked && !showRom) {
    ctx.lineWidth = 1 / z;
    frame().forEach((p, i) => { const b = box(p); ctx.strokeStyle = S.sel.has(i) ? '#ffd84d' : 'rgba(60,207,122,.75)';
      ctx.strokeRect(b.x + .5 / z, b.y + .5 / z, b.w - 1 / z, b.h - 1 / z); });
  }
  if (S.drag && S.drag.marquee) { const m = S.drag.marquee; ctx.strokeStyle = '#4da3ff'; ctx.lineWidth = 1 / z;
    ctx.strokeRect(Math.min(m.x0, m.x1), Math.min(m.y0, m.y1), Math.abs(m.x1 - m.x0), Math.abs(m.y1 - m.y0)); }
  ctx.strokeStyle = '#ff5050'; ctx.lineWidth = 1 / z; ctx.beginPath(); ctx.moveTo(-4, 0); ctx.lineTo(4, 0); ctx.moveTo(0, -4); ctx.lineTo(0, 4); ctx.stroke();
  if (showRom) { ctx.setTransform(1, 0, 0, 1, 0, 0); ctx.fillStyle = '#ffb347'; ctx.font = '12px system-ui'; ctx.fillText('ROM layout (read-only view)', 8, 16); }
}
const sc = $('#sheet'), sctx = sc.getContext('2d');
function drawSheet() {
  if (!S.data) return;
  const z = +$('#sheetZoom').value, W = S.data.sheetW, H = S.data.sheetH;
  sc.width = W * z; sc.height = H * z; sctx.imageSmoothingEnabled = false;
  checker(sctx, W, H, z);
  if (S.sheetImg) sctx.drawImage(S.sheetImg, 0, 0, W * z, H * z);
  const cols = W / 8, nonempty = new Set(S.data.nonempty), usedCur = tilesOf(frame()), usedAny = new Set();
  for (const f of S.frames) for (const t of tilesOf(f)) usedAny.add(t);
  const selT = new Set(); for (const i of S.sel) { const p = frame()[i]; if (p) for (const c of cells(p)) selT.add(c.t); }
  const n = cols * (H / 8);
  for (let t = 0; t < n; t++) {
    const x = (t % cols) * 8 * z, y = Math.floor(t / cols) * 8 * z;
    if (nonempty.has(t) && !usedAny.has(t)) { sctx.fillStyle = 'rgba(255,93,108,.35)'; sctx.fillRect(x, y, 8 * z, 8 * z); }
    sctx.strokeStyle = 'rgba(255,255,255,.08)'; sctx.lineWidth = 1; sctx.strokeRect(x + .5, y + .5, 8 * z - 1, 8 * z - 1);
    if (usedCur.has(t)) { sctx.strokeStyle = '#3ccf7a'; sctx.strokeRect(x + 1.5, y + 1.5, 8 * z - 3, 8 * z - 3); }
    if (selT.has(t)) { sctx.fillStyle = 'rgba(255,216,77,.3)'; sctx.fillRect(x, y, 8 * z, 8 * z); sctx.strokeStyle = '#ffd84d'; sctx.strokeRect(x + .5, y + .5, 8 * z - 1, 8 * z - 1); }
    if ($('#numChk').checked) { sctx.fillStyle = '#fff'; sctx.font = Math.max(8, 3 * z) + 'px monospace'; sctx.fillText(t, x + 2, y + 3 * z + 1); }
  }
  const s = S.sheetSel;
  if (s) { sctx.strokeStyle = '#4da3ff'; sctx.lineWidth = 2; sctx.strokeRect(s.c * 8 * z + 1, s.r * 8 * z + 1, s.cols * 8 * z - 2, s.rows * 8 * z - 2); }
  $('#placeSelBtn').disabled = !s;
  const inactive = [...nonempty].filter(t => !usedAny.has(t)).length;
  $('#sheetName').textContent = S.data.sheet + ` - ${inactive} inactive tile${inactive === 1 ? '' : 's'}`;
}
