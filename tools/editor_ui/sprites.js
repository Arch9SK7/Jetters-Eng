  if (S.sel.size !== 1) { el.innerHTML = `<div class="help">${S.sel.size ? S.sel.size + ' pieces selected - drag or use the arrow keys to move them together.' : 'Click a piece on the canvas or in the list.'}</div>`; return; }
  const i = [...S.sel][0], p = frame()[i]; if (!p) { el.innerHTML = ''; return; }
