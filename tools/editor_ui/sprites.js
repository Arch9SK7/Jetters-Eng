  const d = S.sdrag; S.sdrag = null; if (!d) return; const s = S.sheetSel, cols = S.data.sheetW / 8;
  if (s.cols === 1 && s.rows === 1 && S.sel.size === 1) { pushUndo(); const p = frame()[[...S.sel][0]]; p.tile = s.r * cols + s.c; drawAll(); }
