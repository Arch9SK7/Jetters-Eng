function usePreviewSheet(v) {
  const d = S.data;
  Object.assign(d, {sheet: v.sheet, sheetOk: v.sheetOk, sheetW: v.sheetW, sheetH: v.sheetH, nonempty: v.nonempty});
  S.sheetImg = null;
  if (v.sheetOk) loadImage('/api/png?path=' + encodeURIComponent(v.sheet) + '&v=' + v.sheetMtime).then(i => { S.sheetImg = i; drawAll(); });
  drawAll();
}
function computeWorld() {
  let x0 = -64, y0 = -48, x1 = 64, y1 = 48;
  for (const fs of [S.frames, S.data.romFrames]) for (const f of fs) for (const p of f) {
    const b = box(p); x0 = Math.min(x0, b.x); y0 = Math.min(y0, b.y); x1 = Math.max(x1, b.x + b.w); y1 = Math.max(y1, b.y + b.h);
  }
  const hx = Math.ceil((Math.max(-x0, x1) + 32) / 8) * 8, hy = Math.ceil((Math.max(-y0, y1) + 32) / 8) * 8;
  S.world = {x0: -hx, y0: -hy, w: hx * 2, h: hy * 2};
}
