def run_cmd(fn, args):
    buf = io.StringIO()
    ok = True
    with contextlib.redirect_stdout(buf), contextlib.redirect_stderr(buf):
        try:
            r = fn(args)
            if r is False or (isinstance(r, int) and not isinstance(r, bool) and r != 0):
                ok = False
        except SystemExit as e:
            if e.code not in (None, 0):
                print(e.code)
                ok = False
        except Exception as e:
            print('ERROR: %r' % e)
            ok = False
    return ok, buf.getvalue()


def safe_path(rel):
    p = os.path.normpath(os.path.join(sf.ROOT, rel))
    if not (p == sf.ROOT or p.startswith(sf.ROOT + os.sep)):
        raise ValueError('path outside the project: %s' % rel)
    return p


def png_of(rel):
    """Indexed BMP -> RGBA PNG with colour 0 transparent (1-bit fonts: white glyphs)."""
    im = Image.open(safe_path(rel))
    if im.mode == '1':
        a = im.convert('L')
        rgba = Image.new('RGBA', im.size, (255, 255, 255, 0))
        rgba.putalpha(a)
    else:
        rgba = im.convert('RGBA')
        if im.mode == 'P':
            idx = Image.frombytes('L', im.size, im.tobytes())
            rgba.putalpha(idx.point(lambda v: 0 if v == 0 else 255))
    buf = io.BytesIO()
    rgba.save(buf, 'PNG')
    return buf.getvalue()


def sheet_info(rel):
    full = safe_path(rel)
    if not os.path.exists(full):
        return dict(sheetOk=False, sheetW=256, sheetH=8, nonempty=[], sheetMtime=0)
    tiles, im = sf.load_sheet(rel)
    return dict(sheetOk=True, sheetW=im.size[0], sheetH=im.size[1], sheetMtime=os.path.getmtime(full),
                nonempty=[i for i, t in enumerate(tiles) if any(t)])


