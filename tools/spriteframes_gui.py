SCRIPT_DIR = os.path.join(sf.ROOT, 'script')
WRITE_RE = re.compile(r'^\s*#WRITE\(\s*\w+\s*,\s*\$([0-9A-Fa-f]+)\s*\)')


def script_file_path(name):
    if not re.match(r'^jetters_\d+\.txt$', name):
        raise ValueError('bad script name')
    return os.path.join(SCRIPT_DIR, name)


def read_lines(path):
    raw = open(path, 'rb').read()
    text = raw.decode('utf-8', 'surrogateescape')
    crlf = '\r\n' in text
    return text.split('\n'), crlf


def script_blocks(lines):
    writes = [i for i, l in enumerate(lines) if WRITE_RE.match(l)]
    blocks = []
    for k, i in enumerate(writes):
        start = i + 1
        end = writes[k + 1] if k + 1 < len(writes) else len(lines)
        while end > start:
            s = lines[end - 1].strip()
            if s == '' or s.startswith('//') or s.startswith('#'):
                end -= 1
            else:
                break
        ptr = int(WRITE_RE.match(lines[i]).group(1), 16)
        text = '\n'.join(l.rstrip('\r') for l in lines[start:end])
        blocks.append(dict(i=k, ptr=ptr, line=i + 1, start=start, end=end, text=text,
                           hash=hashlib.md5(text.encode('utf-8', 'surrogateescape')).hexdigest()))
    return blocks


def script_files():
    tbl = cs.load_table(os.path.join(SCRIPT_DIR, 'jetters_eng.tbl'))
    widths = cs.load_widths(os.path.join(sf.ROOT, 'asm', 'Font.asm'))
    out = []
    for f in sorted(os.listdir(SCRIPT_DIR)):
        if not re.match(r'^jetters_\d+\.txt$', f):
            continue
        jmp, size, unknown, _ = cs.scan(os.path.join(SCRIPT_DIR, f), tbl, widths)
        lines, _ = read_lines(os.path.join(SCRIPT_DIR, f))
        title = ''
        for l in lines[:6]:
            m = re.match(r'//BLOCK #\d+ NAME:\s*(.*)', l.strip())
            if m:
                title = m.group(1).strip()
        out.append(dict(name=f, title=title, jmp=jmp, size=size, unknown=sorted(unknown),
                        strings=len(script_blocks(lines))))
    jmps = sorted(x['jmp'] for x in out if x['jmp'] is not None)
    for x in out:
        nxt = [j for j in jmps if x['jmp'] is not None and j > x['jmp']]
        x['room'] = (nxt[0] - x['jmp']) if nxt else None
        x['overlap'] = bool(nxt) and x['jmp'] + x['size'] > nxt[0]
    return out


def width_table():
    """All 256 widths from asm/Font.asm (WidthTable)."""
    vals = []
    try:
        txt = open(os.path.join(sf.ROOT, 'asm', 'Font.asm'), encoding='utf-8', errors='replace').read()
    except OSError:
        return [8] * 256
    m = re.search(r'WidthTable:(.*?)\.endautoregion', txt, re.S)
    body = m.group(1) if m else ''
    for line in body.splitlines():
        line = line.split(';', 1)[0].strip()
        mf = re.match(r'\.fill\s+(\w+)\s*,\s*(\w+)', line)
        md = re.match(r'\.db\s+(.*)', line)
        if mf:
            vals += [int(mf.group(2), 0)] * int(mf.group(1), 0)
        elif md:
            vals += [int(v, 0) for v in md.group(1).split(',') if v.strip()]
    vals = (vals + [8] * 256)[:256]
    return vals


def script_meta():
    tbl_chars, tbl_tags = {}, {}
    for raw in open(os.path.join(SCRIPT_DIR, 'jetters_eng.tbl'), encoding='utf-8', errors='replace'):
        line = raw.rstrip('\r\n').lstrip('/')
        if '=' not in line:
            continue
        k, v = line.split('=', 1)
        if len(k) == 2 and all(c in '0123456789ABCDEFabcdef' for c in k):
            is_tag = len(v) > 2 and v.startswith('<') and v.endswith('>')
            (tbl_tags if is_tag else tbl_chars)[v] = int(k, 16)
    names = {}
    p11 = os.path.join(SCRIPT_DIR, 'jetters_011.txt')
    if os.path.exists(p11):
        lines, _ = read_lines(p11)
        for b in script_blocks(lines):
            idx = (b['ptr'] - 0x1D2EA8) // 4
            if 0 <= idx < 256 and (b['ptr'] - 0x1D2EA8) % 4 == 0:
                t = '\n'.join(l for l in b['text'].split('\n') if not l.strip().startswith('//'))
                names[idx] = re.sub(r'<[^<>]*>', '', t).strip()
    font = 'assets/Font.bmp'
    # dialogue box from the game's own textbox settings (0x081D5C9C): text area 23 x 3 tiles
    return dict(chars=tbl_chars, tags=tbl_tags, widths=width_table(), names=names,
                font=font, fontOk=os.path.exists(safe_path(font)),
                box=dict(width=184, rows=3, lineStep=16, halfStep=8))


def script_file(name):
    lines, crlf = read_lines(script_file_path(name))
    return dict(name=name, crlf=crlf, blocks=[{k: b[k] for k in ('i', 'ptr', 'line', 'text', 'hash')}
                                              for b in script_blocks(lines)])


def save_script(name, edits):
    path = script_file_path(name)
    lines, crlf = read_lines(path)
    blocks = script_blocks(lines)
    eol = '\r' if crlf else ''
    for e in sorted(edits, key=lambda e: -blocks[int(e['i'])]['start']):
        b = blocks[int(e['i'])]
        if b['hash'] != e['hash']:
            raise ValueError('%s changed on disk (string #%d) - reload the file first' % (name, b['i']))
        new = [l + eol for l in e['text'].replace('\r\n', '\n').split('\n')]
        lines[b['start']:b['end']] = new
    data = '\n'.join(lines).encode('utf-8', 'surrogateescape')
    with open(path, 'wb') as f:
        f.write(data)
    return len(edits)


def run_build_bat():
    if os.name != 'nt':
        return False, 'build.bat can only run on Windows.'
    r = subprocess.run(['cmd', '/c', 'build.bat'], cwd=sf.ROOT, input=b'\r\n' * 30,
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=1800)
    out = r.stdout.decode('utf-8', 'replace')
    return r.returncode == 0 and 'Build Complete' in out, out


def launch_rom():
    rom = os.path.join(sf.ROOT, 'jetters_eng.gba')
    if not os.path.exists(rom):
        raise ValueError('jetters_eng.gba not found - build first')
    emu = load_settings().get('emulator', '').strip()
    if emu:
        if not os.path.exists(emu):
            raise ValueError('emulator not found: %s (fix it in Settings)' % emu)
        subprocess.Popen([emu, rom], cwd=os.path.dirname(emu) or None)
        return 'started %s' % os.path.basename(emu)
    open_path('jetters_eng.gba')
    return 'opened jetters_eng.gba with your default program'


def open_path(rel):
    p = safe_path(rel)
    if not os.path.exists(p):
        raise ValueError('not found: %s' % rel)
    if os.name == 'nt':
        os.startfile(p)  # noqa
    elif sys.platform == 'darwin':
        subprocess.Popen(['open', p])
    else:
        subprocess.Popen(['xdg-open', p])


class Handler(BaseHTTPRequestHandler):
    def log_message(self, *a):
        pass

    def send(self, code, body, ctype='application/json'):
        if isinstance(body, (dict, list)):
            body = json.dumps(body).encode()
        elif isinstance(body, str):
            body = body.encode()
        self.send_response(code)
        self.send_header('Content-Type', ctype)
        self.send_header('Cache-Control', 'no-store')
        self.send_header('Content-Length', str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        u = urlparse(self.path)
        q = {k: v[0] for k, v in parse_qs(u.query).items()}
        try:
            if u.path == '/' or u.path.startswith('/ui/'):
                rel = 'index.html' if u.path == '/' else u.path[4:]
                p = os.path.normpath(os.path.join(UI_DIR, rel))
                if not p.startswith(UI_DIR) or not os.path.isfile(p):
                    return self.send(404, {'error': 'not found'})
                ctype = mimetypes.guess_type(p)[0] or 'application/octet-stream'
                if ctype.startswith('text/') or ctype.endswith('javascript'):
                    ctype += '; charset=utf-8'
                return self.send(200, open(p, 'rb').read(), ctype)
            with LOCK:
                if u.path == '/api/state':
                    cfg = sf.load_config()
                    return self.send(200, dict(
                        root=sf.ROOT, windows=os.name == 'nt', settings=load_settings(),
                        sprites=[dict(name=k, tables=v['tables'], note=v.get('note', ''), words=bool(v.get('words')))
                                 for k, v in cfg['sprites'].items()],
                        maps=[dict(name=k, note=v.get('note', '')) for k, v in sf.load_maps_config().get('maps', {}).items()]))
                if u.path == '/api/sprite':
                    t = sf.parse_int(q['table']) if q.get('table') else None
                    return self.send(200, sprite_payload(q['name'], t))
                if u.path == '/api/png':
                    return self.send(200, png_of(q['path']), 'image/png')
                if u.path == '/api/banks':
                    rom = sf.find_rom(sf.load_config())
                    return self.send(200, [dict(e, table='0x%08X' % e['table'], anims='0x%08X' % e['anims'],
                                                gfx='0x%08X' % e['gfx'] if 'gfx' in e else None, pal=None)
                                           for e in sf.bank_entries(rom)])
                if u.path == '/api/map':
                    return self.send(200, map_payload(q['name']))
                if u.path == '/api/script/files':
                    return self.send(200, script_files())
                if u.path == '/api/script/meta':
                    return self.send(200, script_meta())
                if u.path == '/api/script/file':
                    return self.send(200, script_file(q['name']))
            self.send(404, {'error': 'not found'})
        except SystemExit as e:
            self.send(500, {'error': str(e.code)})
        except Exception as e:
            self.send(500, {'error': '%s: %s' % (type(e).__name__, e)})

    def do_POST(self):
        u = urlparse(self.path)
        n = int(self.headers.get('Content-Length', 0))
        body = json.loads(self.rfile.read(n) or b'{}')
        try:
            with LOCK:
                p = u.path
                if p == '/api/save':
                    fp = save_frames(body['name'], sf.parse_int(body['table']), body['frames'])
                    return self.send(200, {'ok': True, 'log': 'saved %s' % fp, 'file': fp})
                if p == '/api/revert':
                    cfg = sf.load_config()
                    name, sc = sf.sprite_cfg(cfg, body['name'])
                    fp = sf.frames_path(name, sf.parse_int(body['table']))
                    if os.path.exists(fp):
                        os.replace(fp, fp + '.bak')
                    return self.send(200, {'ok': True, 'log': 'frames file moved to %s.bak' % os.path.relpath(fp, sf.ROOT)})
                if p == '/api/build':
                    ok, log = run_cmd(sf.cmd_build, [])
                    return self.send(200, {'ok': ok, 'log': log})
                if p == '/api/buildbat':
                    ok, log = run_build_bat()
                    return self.send(200, {'ok': ok, 'log': log})
                if p == '/api/buildtest':
                    ok, log = run_build_bat()
                    if ok:
                        log += '\n' + launch_rom()
                    return self.send(200, {'ok': ok, 'log': log})
                if p == '/api/launch':
                    return self.send(200, {'ok': True, 'log': launch_rom()})
                if p == '/api/settings':
                    s = load_settings()
                    s.update({k: v for k, v in body.items() if k in ('emulator',)})
                    save_settings(s)
                    return self.send(200, {'ok': True, 'log': 'settings saved', 'settings': s})
                if p == '/api/words':
                    ok, log = run_cmd(sf.cmd_words, [body['name']] + (['--force'] if body.get('force') else []))
                    return self.send(200, {'ok': ok, 'log': log})
                if p == '/api/relayout':
                    ok, log = run_cmd(sf.cmd_relayout, [body['name']])
                    return self.send(200, {'ok': ok, 'log': log})
                if p == '/api/open':
                    open_path(body['path'])
                    return self.send(200, {'ok': True, 'log': 'opened %s' % body['path']})
                if p == '/api/addsprite':
                    name, msg = add_sprite(body)
                    return self.send(200, {'ok': True, 'name': name, 'log': ('added sprite %s. %s' % (name, msg)).strip()})
                if p == '/api/map/save':
                    f = save_map(body['name'], body['entries'])
                    return self.send(200, {'ok': True, 'log': 'saved %s' % f})
                if p == '/api/map/add':
                    name = add_map(body)
                    return self.send(200, {'ok': True, 'name': name, 'log': 'added map %s' % name})
                if p == '/api/map/base':
                    set_map_base(body['name'], body['base'])
                    return self.send(200, {'ok': True, 'log': 'tile offset saved'})
                if p == '/api/script/save':
                    n = save_script(body['name'], body['edits'])
                    ok, log = run_cmd(cs.main_args, [])
                    return self.send(200, {'ok': True, 'log': 'saved %d string(s) in %s\n%s' % (n, body['name'], log), 'checkOk': ok})
                if p == '/api/script/check':
                    ok, log = run_cmd(cs.main_args, body.get('args', []))
                    return self.send(200, {'ok': ok, 'log': log})
            self.send(404, {'error': 'not found'})
        except SystemExit as e:
            self.send(400, {'error': str(e.code)})
        except Exception as e:
            self.send(400, {'error': '%s' % e})


def main():
    port = 0
    for a in sys.argv[1:]:
        if a.isdigit():
            port = int(a)
    srv = ThreadingHTTPServer(('127.0.0.1', port), Handler)
    url = 'http://127.0.0.1:%d/' % srv.server_address[1]
    print('Jetters editor running at %s  (close this window to stop it)' % url)
    if '--no-browser' not in sys.argv:
        threading.Timer(0.5, lambda: webbrowser.open(url)).start()
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        pass


if __name__ == '__main__':
    main()
